"""Download a labelled image set for measuring the AI-image detector, from live Wikimedia Commons.

    python scripts/fetch_ai_images.py --out <dir> --ai 40 --real 40

Positives are files in Commons categories whose members are AI-generated (the label is Commons' own category, not ours).
Negatives are random Commons files, almost all ordinary photos or scans; a few may be drawings or diagrams, and some
may themselves be undeclared AI images, so the measured false-alarm rate is an upper-bound estimate, not exact.
Writes <dir>/labels.json mapping file name to {label, title}. Thumbnails are used, as a post would carry a shrunk copy.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from measure_image_match import commons_images  # noqa: E402
from satyasutra.config import load_config  # noqa: E402
from satyasutra.envfile import load_env_file  # noqa: E402
from satyasutra.sources.probe import build_user_agent  # noqa: E402

CATEGORIES = ["Category:AI-generated images", "Category:Images generated by Stable Diffusion", "Category:Images generated by Midjourney",
              "Category:Images generated by DALL-E", "Category:Images generated by Flux", "Category:Images generated by Imagen"]
FILE_NAMESPACE = 6
ACCEPT = {"image/jpeg", "image/png"}
PAUSE_S = 1.0


def category_images(cfg, http: httpx.Client, wanted: int, categories: list[str]) -> list[tuple[str, bytes]]:
    c = cfg.runtime.provenance.commons
    out: list[tuple[str, bytes]] = []
    for cat in categories:
        cont: dict = {}
        while len(out) < wanted:
            params = {"action": "query", "format": "json", "generator": "categorymembers", "gcmtitle": cat, "gcmtype": "file", "gcmlimit": 20,
                      "prop": "imageinfo", "iiprop": "url|mime", "iiurlwidth": c.thumb_width} | cont
            r = http.get(c.endpoint, params=params)
            r.raise_for_status()
            body = r.json()
            for page in body.get("query", {}).get("pages", {}).values():
                info = (page.get("imageinfo") or [{}])[0]
                if info.get("mime") not in ACCEPT or not info.get("thumburl") or len(out) >= wanted:
                    continue
                time.sleep(PAUSE_S)
                try:
                    img = http.get(info["thumburl"])
                except httpx.HTTPError:
                    continue
                if img.status_code == httpx.codes.OK:
                    out.append((page["title"], img.content))
            cont = body.get("continue", {})
            if not cont:
                break
        print(f"  {cat}: {len(out)} so far", flush=True)
        if len(out) >= wanted:
            break
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--ai", type=int, default=40)
    ap.add_argument("--real", type=int, default=40)
    args = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    load_env_file(ROOT / ".env")
    cfg = load_config()
    args.out.mkdir(parents=True, exist_ok=True)
    labels: dict[str, dict] = {}
    with httpx.Client(timeout=60, headers={"User-Agent": build_user_agent(cfg.runtime.probe.user_agent)}) as http:
        sets = [("ai", category_images(cfg, http, args.ai, CATEGORIES)), ("real", commons_images(cfg, http, args.real))]
    for label, items in sets:
        for i, (title, data) in enumerate(items):
            name = f"{label}_{i:03d}.img"
            (args.out / name).write_bytes(data)
            labels[name] = {"label": label, "title": title}
    (args.out / "labels.json").write_text(json.dumps(labels, indent=1), encoding="utf-8")
    print(f"saved {sum(v['label'] == 'ai' for v in labels.values())} AI and {sum(v['label'] == 'real' for v in labels.values())} real images to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
