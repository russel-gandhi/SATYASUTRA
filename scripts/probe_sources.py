"""Run first. Shows which configured sources are reachable from this machine right now.

    python scripts/probe_sources.py [--json] [--write-report] [--strict]

--write-report  also writes docs/probe_results.md (commit it when a ticket closes on this output)
--strict        exit 1 if any Tier 1 or Tier 2 source is unreachable
Keys come from environment variables named in config/sources.yaml; sources needing one say "needs_key".
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from satyasutra.config import load_config  # noqa: E402
from satyasutra.sources import probe_all  # noqa: E402


def render(results) -> str:
    header = f"{'source':<22}{'tier':<6}{'state':<14}{'http':<6}{'ms':<7}detail"
    lines = [header, "-" * len(header)]
    for r in results:
        lines.append(
            f"{r.source_id:<22}{r.tier:<6}{r.state:<14}{str(r.http_status or '-'):<6}{str(r.latency_ms or '-'):<7}{r.detail}"
        )
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--write-report", action="store_true")
    parser.add_argument("--strict", action="store_true")
    args = parser.parse_args(argv)

    results = probe_all(load_config())
    if args.json:
        print(json.dumps([r.as_dict() for r in results], indent=2))
    else:
        print(render(results))

    if args.write_report:
        stamp = results[0].checked_at if results else ""
        body = (
            "# Probe results\n\nGenerated by `scripts/probe_sources.py --write-report`. "
            "This is what this machine could reach at the time shown; it is not a promise about any other machine or day.\n\n"
            f"Checked at: {stamp}\n\n```\n{render(results)}\n```\n"
        )
        out = ROOT / "docs" / "probe_results.md"
        out.write_text(body, encoding="utf-8")
        print(f"\nwrote {out.relative_to(ROOT)}")

    if args.strict and any(r.tier <= 2 and r.state == "unreachable" for r in results):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
